export default function AmenityIcon({
  name,
  label,
  index = 0,
  className,
}: {
  name: string;
  label: string;
  index?: number;
  className?: string;
}) {
  const ref = useRef<SVGSVGElement>(null);
  const [looping, setLooping] = useState(false);

  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    const observer = new IntersectionObserver(
      ([entry]) => {
        if (entry.isIntersecting) {
          setLooping(true);
          observer.disconnect();
        }
      },
      { threshold: 0.4 }
    );
    observer.observe(el);
    return () => observer.disconnect();
  }, []);

  return (
    <svg
      ref={ref}
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 256 256"
      className={className}
      role="img"
      aria-label={label}
    >
      <title>{label}</title>
      <path
        d={paths[name]}
        pathLength={1}
        fill="#ffffff"
        stroke="#ffffff"
        strokeWidth={6}
        strokeLinecap="round"
        strokeLinejoin="round"
        style={{
          strokeDasharray: 1,
          strokeDashoffset: 1,
          fillOpacity: 0,
          animation: looping
            ? `icon-draw-loop 4s ease-in-out ${(index % 4) * 0.3}s infinite`
            : "none",
        }}
      />
    </svg>
  );
}
